CREATE TABLE improvement_practice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id UUID NOT NULL,
    session_id UUID NOT NULL,
    improvement_id BIGINT NOT NULL,
    question_number INTEGER NOT NULL,
    question_text TEXT NOT NULL,
    original_answer TEXT NOT NULL,
    submitted_answer TEXT,
    status VARCHAR(20) NOT NULL,
    score INTEGER,
    summary VARCHAR(300),
    detail TEXT,
    quote TEXT,
    fail_reason VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_improvement_practice PRIMARY KEY (id),
    CONSTRAINT fk_improvement_practice_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_improvement_practice_session FOREIGN KEY (session_id) REFERENCES interview_session (id),
    CONSTRAINT fk_improvement_practice_improvement FOREIGN KEY (improvement_id) REFERENCES feedback_improvement (id) ON DELETE CASCADE,
    CONSTRAINT ck_improvement_practice_score CHECK (score IS NULL OR score BETWEEN 1 AND 100)
);

CREATE INDEX idx_improvement_practice_user_created
    ON improvement_practice (user_id, created_at DESC);

CREATE INDEX idx_improvement_practice_status_updated
    ON improvement_practice (status, updated_at);
