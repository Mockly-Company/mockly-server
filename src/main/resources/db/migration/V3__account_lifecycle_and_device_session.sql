-- 기존 운영/신규 DB의 단일 컬럼(device_id) UNIQUE 제약을 제약명 차이와 무관하게 안전하게 제거
ALTER TABLE session DROP CONSTRAINT IF EXISTS uk_session_device_id;
ALTER TABLE session DROP CONSTRAINT IF EXISTS session_device_id_key;
ALTER TABLE session DROP CONSTRAINT IF EXISTS uk_session_user_device;
ALTER TABLE session ADD CONSTRAINT uk_session_user_device UNIQUE (user_id, device_id);

ALTER TABLE users ADD COLUMN IF NOT EXISTS job_category VARCHAR(30);
ALTER TABLE users ADD COLUMN IF NOT EXISTS job_role VARCHAR(30);
ALTER TABLE users ADD COLUMN IF NOT EXISTS experience_years INTEGER;
ALTER TABLE users ADD COLUMN IF NOT EXISTS terms_agreed_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE IF NOT EXISTS user_agreement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id UUID NOT NULL,
    agreement_type VARCHAR(30) NOT NULL,
    agreed BOOLEAN NOT NULL,
    agreed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_user_agreement PRIMARY KEY (id),
    CONSTRAINT fk_user_agreement_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_user_agreement_user_type UNIQUE (user_id, agreement_type)
);
