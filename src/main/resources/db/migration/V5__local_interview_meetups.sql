CREATE TABLE local_interview_meetup (
    id UUID NOT NULL,
    host_user_id UUID NOT NULL,
    title VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    job_category VARCHAR(30) NOT NULL,
    job_role VARCHAR(30) NOT NULL,
    interview_type VARCHAR(30) NOT NULL,
    experience_level VARCHAR(20) NOT NULL,
    location_status VARCHAR(30) NOT NULL,
    meeting_type VARCHAR(20) NOT NULL,
    place_name VARCHAR(120) NOT NULL,
    address_label VARCHAR(200) NOT NULL,
    full_address VARCHAR(300),
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
    recruit_deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    current_participants INTEGER NOT NULL,
    max_participants INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_local_interview_meetup PRIMARY KEY (id),
    CONSTRAINT fk_meetup_host_user FOREIGN KEY (host_user_id) REFERENCES users (id),
    CONSTRAINT ck_meetup_max_participants CHECK (max_participants BETWEEN 2 AND 8),
    CONSTRAINT ck_meetup_current_participants CHECK (current_participants >= 1 AND current_participants <= max_participants)
);

CREATE INDEX idx_meetup_lat_lng
    ON local_interview_meetup (latitude, longitude);

CREATE INDEX idx_meetup_starts_at
    ON local_interview_meetup (starts_at);

CREATE TABLE local_interview_meetup_participant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    meetup_id UUID NOT NULL,
    user_id UUID NOT NULL,
    is_host BOOLEAN NOT NULL,
    status VARCHAR(20) NOT NULL,
    message VARCHAR(300),
    job_category VARCHAR(30) NOT NULL,
    job_role VARCHAR(30) NOT NULL,
    experience_years INTEGER NOT NULL,
    experience_level VARCHAR(20) NOT NULL,
    applied_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_local_interview_meetup_participant PRIMARY KEY (id),
    CONSTRAINT fk_meetup_participant_meetup FOREIGN KEY (meetup_id) REFERENCES local_interview_meetup (id) ON DELETE CASCADE,
    CONSTRAINT fk_meetup_participant_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_meetup_participant_user UNIQUE (meetup_id, user_id)
);

CREATE INDEX idx_meetup_participant_user
    ON local_interview_meetup_participant (user_id, created_at DESC);
